@dataclass
class ReflexConfig:
    """Contact-driven reflexes for the analytic gait (Cruse's Walknet / Espenschied's insect
    reflexes). These are OFF unless a config is attached to the GaitController, so the firmware
    mirror in gait.h stays in parity until they prove themselves.

    They address what a blind gait cannot: touchdown TIMING. The engine assumes ground at a fixed
    body-frame height, so on uneven terrain a leg either lands early (body lurches) or swings
    through air and lands late (support gap). A foot switch knows before the body does.
    """

    # MEASURED (2026-07-26, bench_terrain.py, 6 seeds), on the classical gait with no policy:
    #   reach + ground_follow  raises the curb ceiling 30 -> 40 mm (0/6 -> 6/6) and roughly doubles
    #                          forward reach at a 40 mm step (0.67 -> 1.40 m). A 25 mm taller stance
    #                          alone does NOT do this, so it is genuine reflex behaviour. Cost: flat
    #                          progress -0.12 (p<0.001); the rough-FIELD gain is not significant.
    #   elevator               inert with foot-bottom sensors: a switch under the foot senses ground
    #                          beneath it, not an obstacle in front of the shin. It needs a shin
    #                          bumper or motor-current sensing to fire at all. Left on: it is free.
    #   slow_when_unsupported  never showed a benefit; off.
    search: bool = True            # keep reaching down until the foot actually takes load
    ground_follow: bool = True     # carry that reach through stance, so the leg accommodates
    elevator: bool = True          # contact while the foot should be clear -> lift higher
    slow_when_unsupported: bool = False  # shared-clock brake while too few feet are loaded
    # Holding a leg's phase until touchdown is the textbook version, but it fires on EVERY swing --
    # the planned trajectory returns the foot to exactly nominal height, where it is not yet loaded --
    # so it desynchronizes a gait that was already correct and costs progress on flat ground.
    # Reaching further down needs no phase change, so the hold is off by default.
    hold_phase: bool = False

    # Asymmetric debounce: a touchdown is a real force and is believed immediately, while "no ground
    # here" must survive `debounce` consecutive samples. Debouncing both directions just adds delay
    # to the one event that needs to stop the reach promptly.
    debounce: int = 2              # consecutive OPEN samples before concluding the ground is missing

    # Reach/release form a bang-bang regulator on contact rather than a one-shot probe. Reaching
    # alone overshoots by the sensing + actuation lag (~20 mm at 250 mm/s) and stance then holds that
    # over-extension, which is what made reflexes cost progress on flat ground; backing off while
    # loaded cancels it without having to know the lag.
    search_rate: float = 250.0     # mm/s reach down while the foot should be loaded but is not
    release_rate: float = 90.0     # mm/s back off while it IS loaded
    search_max: float = 30.0       # mm
    hold_max_s: float = 0.08       # s before entering stance anyway -- a dead sensor must never
                                   # deadlock the gait (only used when hold_phase is on)
    elev_step: float = 12.0        # mm of extra step height per bump
    elev_max: float = 35.0
    elev_decay: float = 0.6        # retained fraction after a clean swing
    slow_factor: float = 0.45      # phase-rate multiplier when support is missing

    # The elevator triggers on the PLANNED foot height, not on swing phase: at the start of swing the
    # foot is legitimately still touching the ground it just left, so a phase window fires constantly
    # on flat ground. Height is the physical criterion -- "should this foot be clear right now?".
    elev_trigger: float = 12.0     # mm of planned lift above which contact means an obstacle
    # The reach must fire only when a foot is genuinely LATE, never merely "not loaded yet". Contact
    # force needs a step or two to build even on flat ground, so reaching on instantaneous absence
    # digs every foot into the floor on every stride. Waiting `search_grace` steps past the planned
    # touchdown costs nothing on flat and still leaves most of stance to find a hole.
    search_grace: int = 3          # control steps past planned touchdown before reaching down
    search_window: float = 0.5     # give up once this fraction of stance has elapsed


def set_gait(gait: GaitState) -> None:
    """Port of GaitController::setGait — fills offset/stand_frac for the gait type."""
    if gait.gait_type == TRI_GATE:
        gait.offset = np.array([0.0, 0.52, 0.08, 0.58, 0.16, 0.66])
        gait.stand_frac = 3.1 / 6.0
    elif gait.gait_type == BI_GATE:
        gait.offset = np.array([0.0, 1 / 3, 2 / 3, 2 / 3, 1 / 3, 0.0])
        gait.stand_frac = 2.1 / 6.0
    elif gait.gait_type == WAVE:
        gait.offset = np.array([0.0, 1 / 6, 2 / 6, 5 / 6, 4 / 6, 3 / 6])
        gait.stand_frac = 5.0 / 6.0
    elif gait.gait_type == RIPPLE:
        gait.offset = np.array([0.0, 4 / 6, 2 / 6, 1 / 6, 5 / 6, 3 / 6])
        gait.stand_frac = 5.0 / 6.0
    elif gait.gait_type == TUNED:
        tuned = load_tuned_gait()
        gait.offset = tuned.offset.copy()
        gait.stand_frac = tuned.stand_frac


# Deadbands for "the gait is commanded to move", mirroring GAIT_STRIDE_DEADBAND_MM and
# GAIT_YAW_DEADBAND_RAD in firmware/include/gait.h.
# Stride is millimetres of foot travel, yaw radians of body rotation per stance; 0.005 rad across the
# 171 mm leg radius is 0.9 mm of foot travel, the same order as the stride deadband.
STRIDE_DEADBAND_MM = 2.0
YAW_DEADBAND_RAD = 0.005


def gait_is_commanded(gait: GaitState) -> bool:
    return (
        abs(gait.step_x) >= STRIDE_DEADBAND_MM
        or abs(gait.step_y) >= STRIDE_DEADBAND_MM
        or abs(gait.step_angle) >= YAW_DEADBAND_RAD
    )


@dataclass(frozen=True)
class GaitEnvelope:
    """The stroke geometry gait_envelope.h carries, read from the JSON export_envelope.py writes beside it."""

    walkable: np.ndarray  # [s1][h][fd]
    stroke_max: np.ndarray  # [axis][s1][h][fd], axis 0 forward (mm), 1 lateral (mm), 2 yaw (rad)
    kappa_swing: np.ndarray  # [axis][s1][h][fd][k], sample k at (k + 1) / STROKE_SAMPLES of stroke_max
    kappa_stance: np.ndarray  # same layout as kappa_swing
    stand_frac: np.ndarray  # [gait]
    servo_rad_s: float
    cadence_max: float
    default_speed_fraction: float


ENVELOPE_AXES = ("forward", "lateral", "yaw")
GAIT_ENVELOPE_PATH = os.path.join(os.path.dirname(__file__), "..", "resources", "gait_envelope.json")

# The stroke at stride -1, as a share of the speed-optimal one at stride 0 (gait_speed.h)
MIN_STRIDE_SHARE = 0.3


@lru_cache(maxsize=None)
def load_gait_envelope() -> GaitEnvelope:
    with open(GAIT_ENVELOPE_PATH) as f:
        table = json.load(f)

    def per_axis(key):
        return np.array([table[key][axis] for axis in ENVELOPE_AXES])

    return GaitEnvelope(
        walkable=np.array(table["walkable"], dtype=bool),
        stroke_max=per_axis("stroke_max"),
        kappa_swing=per_axis("kappa_swing"),
        kappa_stance=per_axis("kappa_stance"),
        stand_frac=np.array(table["stand_frac"]),
        servo_rad_s=table["servo_rad_s"],
        cadence_max=table["cadence_max"],
        default_speed_fraction=table["default_speed_fraction"],
    )


def _envelope_cell(command: float) -> tuple[int, float]:
    """Port of gait_speed_detail::locate: a grid point belongs to the cell above it, the last closes the one below."""
    cells = load_gait_envelope().walkable.shape[0] - 1
    pos = (min(max(command, -1.0), 1.0) + 1.0) * (cells / 2.0)
    index = min(int(pos), cells - 1)
    return index, pos - index


def _cell_walkable(s1: tuple[int, float], h: tuple[int, float], fd: tuple[int, float]) -> bool:
    corners = load_gait_envelope().walkable[s1[0]:s1[0] + 2, h[0]:h[0] + 2, fd[0]:fd[0] + 2]
    return bool(corners.all())


def _trilinear(table: np.ndarray, s1: tuple[int, float], h: tuple[int, float], fd: tuple[int, float]) -> np.ndarray:
    """Same lerp order as gait_speed_detail::trilinear: along fd, then h, then s1. A table with a trailing sample axis
    is interpolated per sample."""
    def lerp(a, b, t):
        return a + (b - a) * t

    along_fd = [[lerp(table[s1[0] + i, h[0] + j, fd[0]], table[s1[0] + i, h[0] + j, fd[0] + 1], fd[1])
                 for j in range(2)] for i in range(2)]
    return lerp(lerp(along_fd[0][0], along_fd[0][1], h[1]), lerp(along_fd[1][0], along_fd[1][1], h[1]), s1[1])


def posture_walkable(s1: float, h: float, fd: float) -> bool:
    """Port of postureWalkable (gait_speed.h): the posture's cell has eight walkable corners."""
    return _cell_walkable(_envelope_cell(s1), _envelope_cell(h), _envelope_cell(fd))


def _kappa_at_stroke(samples: np.ndarray, fraction: float) -> float:
    """Port of gait_speed_detail::kappaAtStroke: the running maximum of the samples up to the stroke fraction, linear
    between them, and the first sample below it."""
    position = fraction * len(samples) - 1.0
    if not position > 0.0:
        return float(samples[0])
    index = min(int(position), len(samples) - 2)
    below = float(samples[:index + 1].max())
    above = max(below, float(samples[index + 1]))
    return below + (above - below) * (position - index)


def _top_cadence(gait_type: int, kappa_swing: float, kappa_stance: float) -> float:
    """Port of gait_speed_detail::topCadence: the fastest cadence at which no joint passes the servo's speed."""
    env = load_gait_envelope()
    d = float(env.stand_frac[gait_type])
    return min(env.servo_rad_s / max(kappa_swing / (1.0 - d), kappa_stance / d), env.cadence_max)


def envelope_at(gait_type: int, axis: int, s1: float, h: float, fd: float,
                stride: float) -> tuple[float, float, float]:
    """Port of envelopeAt: (v_max, stroke, cadence) of the stroke the stride picks on the axis at the posture; 0 the
    speed-optimal stroke sample, +1 the longest stroke, -1 MIN_STRIDE_SHARE of the speed-optimal one. Empty outside
    walkable cells and for TUNED/AUTO."""
    if not TRI_GATE <= gait_type <= RIPPLE or not 0 <= axis <= 2:
        return 0.0, 0.0, 0.0
    cells = _envelope_cell(s1), _envelope_cell(h), _envelope_cell(fd)
    if not _cell_walkable(*cells):
        return 0.0, 0.0, 0.0
    env = load_gait_envelope()
    stroke_max = float(_trilinear(env.stroke_max[axis], *cells))
    if stroke_max <= 0.0:
        return 0.0, 0.0, 0.0
    swing, stance = _trilinear(env.kappa_swing[axis], *cells), _trilinear(env.kappa_stance[axis], *cells)
    samples = len(swing)

    def cadence_at(fraction):
        return _top_cadence(gait_type, _kappa_at_stroke(swing, fraction), _kappa_at_stroke(stance, fraction))

    optimal, fastest = 0, 0.0
    for n in range(samples):
        # The top speed is stroke * cadence / d, and d is the gait's alone.
        speed = (n + 1) * cadence_at((n + 1) / samples)
        if speed > fastest:
            optimal, fastest = n, speed
    optimal_stroke = (optimal + 1) / samples * stroke_max
    stride = min(max(stride, -1.0), 1.0)
    if stride >= 0.0:
        stroke = optimal_stroke + stride * (stroke_max - optimal_stroke)
    else:
        stroke = optimal_stroke * (1.0 + stride * (1.0 - MIN_STRIDE_SHARE))
    cadence = cadence_at(stroke / stroke_max)
    return stroke * cadence / float(env.stand_frac[gait_type]), stroke, cadence


def clamp_posture(s1: float, h: float, fd: float) -> tuple[float, float, float]:
    """Port of clampPosture (clampAlongRay with postureWalkable): the posture scaled toward neutral to the outermost
    walkable point on its ray, found by a scan from outside and refined by bisection against the step above."""
    scan_steps, refine_steps = 32, 5
    s1, h, fd = (min(max(v, -1.0), 1.0) for v in (s1, h, fd))
    if posture_walkable(s1, h, fd):
        return s1, h, fd
    step = scan_steps - 1
    while step > 0 and not posture_walkable(s1 * step / scan_steps, h * step / scan_steps, fd * step / scan_steps):
        step -= 1
    inside, outside = step / scan_steps, (step + 1) / scan_steps
    for _ in range(refine_steps):
        mid = 0.5 * (inside + outside)
        if posture_walkable(s1 * mid, h * mid, fd * mid):
            inside = mid
        else:
            outside = mid
    return s1 * inside, h * inside, fd * inside


def speed_fraction(s: float) -> float:
    """Port of speedFraction: stop at s = -1, the default fraction at 0, the top speed at +1."""
    s = min(max(s, -1.0), 1.0)
    default = load_gait_envelope().default_speed_fraction
    return default * (1.0 + s) if s < 0.0 else default + (1.0 - default) * s


def _stick_shares(lx: float, ly: float, rx: float, s: float) -> list[float]:
    """Port of gait_speed_detail::stickShares: the stick as a share of each axis's top speed, in envelope order."""
    length = max(1.0, abs(lx) + abs(ly) + abs(rx))
    return [speed_fraction(s) * abs(v) / length for v in (ly, lx, rx)]


def _walk_at_shares(gait_type: int, share: list[float], lx: float, ly: float, rx: float, s1: float, h: float,
                    fd: float, stride: float) -> tuple[float, float, float, float]:
    """Port of gait_speed_detail::walkAtShares: the walk at share[axis] of each axis's top speed at the stride, signed
    by the stick: +lx strafes right, +ly walks forward and +rx turns clockwise. Each axis walks its share of the total
    share of its stroke, at the total share of the slowest top cadence among those axes."""
    used, stroke = [0.0] * 3, [0.0] * 3
    total, slowest = 0.0, load_gait_envelope().cadence_max
    for axis in range(3):
        if share[axis] <= 0.0:
            continue
        _, axis_stroke, cadence = envelope_at(gait_type, axis, s1, h, fd, stride)
        if axis_stroke <= 0.0:
            continue
        used[axis] = share[axis]
        stroke[axis] = axis_stroke
        slowest = min(slowest, cadence)
        total += used[axis]
    if total <= 0.0:
        return 0.0, 0.0, 0.0, 0.0
    stroke = [stroke[axis] * (used[axis] / total) for axis in range(3)]
    return math.copysign(stroke[1], lx), math.copysign(stroke[0], ly), -math.copysign(stroke[2], rx), total * slowest


def classic_walk_target(gait_type: int, lx: float, ly: float, rx: float, s: float, s1: float, h: float,
                        fd: float, stride: float) -> tuple[float, float, float, float]:
    """Port of classicWalkTarget (gait_speed.h): (step_x, step_y, step_angle, phase_rate) for a classic gait at the
    stick's share of each axis's top speed at the posture and stride."""
    if not TRI_GATE <= gait_type <= RIPPLE:
        return 0.0, 0.0, 0.0, 0.0
    return _walk_at_shares(gait_type, _stick_shares(lx, ly, rx, s), lx, ly, rx, s1, h, fd, stride)


@dataclass
class AutoDemand:
    """Port of AutoDemand (gait_speed.h): the speed AUTO walks, the stick's share of BI's top speed on each axis."""
    speed: list[float]  # forward and lateral in mm/s, yaw in rad/s
    speed01: float  # its share of BI's top speed, summed over the axes like the stick


def auto_demand(lx: float, ly: float, rx: float, s: float, s1: float, h: float, fd: float,
                stride: float) -> AutoDemand:
    """Port of autoDemand."""
    demand = AutoDemand([0.0] * 3, 0.0)
    for axis, share in enumerate(_stick_shares(lx, ly, rx, s)):
        v_max = envelope_at(BI_GATE, axis, s1, h, fd, stride)[0]
        if v_max <= 0.0:
            continue
        demand.speed[axis] = share * v_max
        demand.speed01 += share
    return demand


def _demand_shares(gait_type: int, demand: AutoDemand, s1: float, h: float, fd: float,
                   stride: float) -> list[float] | None:
    """Port of gait_speed_detail::demandShares: None when the gait cannot walk an axis the demand asks for."""
    share = [0.0] * 3
    for axis in range(3):
        if demand.speed[axis] <= 0.0:
            continue
        v_max = envelope_at(gait_type, axis, s1, h, fd, stride)[0]
        if v_max <= 0.0:
            return None
        share[axis] = demand.speed[axis] / v_max
    return share


def select_auto_gait(demand: AutoDemand, current: int, s1: float, h: float, fd: float, stride: float) -> int:
    """Port of selectAutoGait: the slowest of RIPPLE, TRI and BI whose top speed at the stride covers the demand, a
    gait other than the one in effect with AUTO_HYSTERESIS to spare."""
    for gait_type in (RIPPLE, TRI_GATE):
        share = _demand_shares(gait_type, demand, s1, h, fd, stride)
        if share is not None and sum(share) <= (1.0 if gait_type == current else 1.0 - AUTO_HYSTERESIS):
            return gait_type
    return BI_GATE


def auto_walk_target(gait_type: int, demand: AutoDemand, lx: float, ly: float, rx: float, s1: float, h: float,
                     fd: float, stride: float) -> tuple[float, float, float, float]:
    """Port of autoWalkTarget: the demand's share of the gait's own top speeds at the stride, capped at its top."""
    if not TRI_GATE <= gait_type <= RIPPLE:
        return 0.0, 0.0, 0.0, 0.0
    share = []
    for axis in range(3):
        v_max = envelope_at(gait_type, axis, s1, h, fd, stride)[0]
        share.append(demand.speed[axis] / v_max if v_max > 0.0 else 0.0)
    total = sum(share)
    if total > 1.0:
        share = [axis_share / total for axis_share in share]
    return _walk_at_shares(gait_type, share, lx, ly, rx, s1, h, fd, stride)


def command_to_walk_gait(lx, ly, rx, s, s1, gait: GaitState, h: float = 0.0, fd: float = 0.0,
                         stride: float = 0.0) -> float:
    """Port of MotionService::handleCommand WALK branch (firmware/include/motion.h).

    Writes the target gait command into `gait`, whose gait_type selects the classic or the TUNED
    branch, and returns the target body height zm in mm. A classic gait walks the posture clamped
    to the walkable region and the stride, both taken at once: MotionService's pause while a new posture
    is stepped into, and its slew of the stride while walking, are not ported.
    """
    if gait.gait_type == TUNED:
        tuned = load_tuned_gait()
        cmd = (ly * TUNED_CMD_VX_MAX, lx * TUNED_CMD_VY_MAX, -rx * TUNED_CMD_YAW_MAX)
        a = tuned.schedule.gait_action(cmd)
        gait.step_x = float(a[0]) * TUNED_STEP_XY_MM
        gait.step_y = float(a[1]) * TUNED_STEP_XY_MM
        gait.step_angle = float(a[2]) * TUNED_STEP_ANGLE_RAD
        gait.step_height = float(np.clip(tuned.step_height_mm + s1 * TUNED_LIFT_TRIM_MM, *TUNED_STEP_HEIGHT_MM))
        gait.step_depth = tuned.step_depth_mm
        gait.step_speed = s + 1.0
        lo, hi = TUNED_PHASE_RATE
        gait.phase_rate = lo + (float(a[5]) + 1.0) * 0.5 * (hi - lo)
        return -tuned.ride_mm
    s1, h, fd = clamp_posture(s1, h, fd)
    gait.step_x, gait.step_y, gait.step_angle, gait.phase_rate = classic_walk_target(
        gait.gait_type, lx, ly, rx, s, s1, h, fd, stride)
    gait.step_height = (s1 + 1.0) * 20.0
    gait.step_depth = DEFAULT_STEP_DEPTH
    # The envelope sets the cadence; step_speed is left to pace a stance change.
    gait.step_speed = 1.0
    return h * 50.0


def _swing_progress(phase: float, stand_frac: float) -> float:
    return (phase - stand_frac) / (1.0 - stand_frac)


def _lerp(start: float, end: float, t: float) -> float:
    """Same operation order as lerpf (firmware/include/utils/math_utils.h)."""
    return (1.0 - t) * start + t * end


def _approach(current: float, target: float, alpha: float, eps: float) -> float:
    nxt = _lerp(current, target, alpha)
    return target if abs(target - nxt) <= eps else nxt


def approach_gait_command(current: GaitState, target: GaitState, dt: float,
                          tau: float = GAIT_COMMAND_TAU_S) -> None:
    """Port of approachGaitCommand: eases the live command toward the target, first order."""
    a = 1.0 if tau <= 0.0 or dt <= 0.0 else 1.0 - math.exp(-dt / tau)
    current.step_x = _approach(current.step_x, target.step_x, a, GAIT_SNAP_MM)
    current.step_y = _approach(current.step_y, target.step_y, a, GAIT_SNAP_MM)
    current.step_angle = _approach(current.step_angle, target.step_angle, a, GAIT_SNAP_RAD)
    current.step_speed = _approach(current.step_speed, target.step_speed, a, GAIT_SNAP_RATE)
    current.step_height = _approach(current.step_height, target.step_height, a, GAIT_SNAP_MM)
    current.step_depth = _approach(current.step_depth, target.step_depth, a, GAIT_SNAP_DEPTH)
    # 0 means "derive cadence from stride", so only two explicit rates are eased between.
    if current.phase_rate > 0.0 and target.phase_rate > 0.0:
        current.phase_rate = _approach(current.phase_rate, target.phase_rate, a, GAIT_SNAP_RATE)
    else:
        current.phase_rate = target.phase_rate


class GaitCommandRamp:
    """Port of GaitCommandRamp (gait.h): every change eases first order, except a stop, which starts from the walk as
    it is, eases the stroke out through two first-order stages and scales the cadence with the share of the stroke left.
    A walk on the stride law (phase_rate 0) keeps it."""

    def __init__(self):
        self._stopping = False
        self._from = GaitState()
        self._stage = GaitState()

    def step(self, live: GaitState, target: GaitState, dt: float, tau: float = GAIT_COMMAND_TAU_S) -> None:
        if target.phase_rate > 0.0 or gait_is_commanded(target) or not gait_is_commanded(live):
            self._stopping = False
            approach_gait_command(live, target, dt, tau)
            return
        if not self._stopping:
            self._stopping = True
            self._from = copy.deepcopy(live)
            self._stage = copy.deepcopy(live)
        a = 1.0 if tau <= 0.0 or dt <= 0.0 else 1.0 - math.exp(-dt / tau)
        self._stage.step_x = _approach(self._stage.step_x, target.step_x, a, GAIT_SNAP_MM)
        self._stage.step_y = _approach(self._stage.step_y, target.step_y, a, GAIT_SNAP_MM)
        self._stage.step_angle = _approach(self._stage.step_angle, target.step_angle, a, GAIT_SNAP_RAD)
        eased = copy.deepcopy(target)
        eased.step_x, eased.step_y, eased.step_angle = self._stage.step_x, self._stage.step_y, self._stage.step_angle
        approach_gait_command(live, eased, dt, tau)
        live.phase_rate = self._from.phase_rate * self._stroke_left(live) if gait_is_commanded(live) else 0.0

    def _stroke_left(self, g: GaitState) -> float:
        """The share of the stop's starting stroke left, along the axis that started furthest past its deadband."""
        f = self._from
        x, y = abs(f.step_x) / STRIDE_DEADBAND_MM, abs(f.step_y) / STRIDE_DEADBAND_MM
        yaw = abs(f.step_angle) / YAW_DEADBAND_RAD
        if x >= y and x >= yaw:
            return abs(g.step_x / f.step_x)
        if y >= yaw:
            return abs(g.step_y / f.step_y)
        return abs(g.step_angle / f.step_angle)


class Kinematics:
    """Port of firmware/include/kinematics.h :: Kinematics."""

    def __init__(self):
        self.mount_x = MOUNT_X
        self.mount_y = MOUNT_Y
        self.root_j1 = ROOT_TO_J1
        self.j1_j2 = J1_TO_J2
        self.j2_j3 = J2_TO_J3
        self.j3_tip = J3_TO_TIP
        a = np.deg2rad(MOUNT_ANGLE_DEG)
        self.ca = np.cos(a)
        self.sa = np.sin(a)
        self.mount_pos = np.column_stack([self.mount_x, self.mount_y, np.zeros(6)])

    @staticmethod
    def transformation_matrix(b: BodyState) -> np.ndarray:
        """Port of get_transformation_matrix (firmware). w = T @ [x,y,z,1]."""
        co, so = math.cos(b.omega), math.sin(b.omega)
        cp, sp = math.cos(b.phi), math.sin(b.phi)
        cs, ss = math.cos(b.psi), math.sin(b.psi)
        T = np.array(
            [
                [cp * cs, -cp * ss, sp, b.xm],
                [so * sp * cs + ss * co, -so * sp * ss + co * cs, -so * cp, b.ym],
                [so * ss - sp * co * cs, so * cs + sp * ss * co, co * cp, b.zm],
                [0.0, 0.0, 0.0, 1.0],
            ]
        )
        return T

    def inverse_kinematics(self, b: BodyState, degrees: bool = True) -> np.ndarray:
        """Returns 18 joint angles (6 legs x [coxa, femur, tibia]).

        Faithful port of Kinematics::inverseKinematics; firmware returns degrees.
        """
        T = self.transformation_matrix(b)
        ang = np.zeros((6, 3))
        for i in range(6):
            w = T @ b.feet[i]
            wx = w[0] - self.mount_pos[i][0]
            wy = w[1] - self.mount_pos[i][1]
            wz = w[2] - self.mount_pos[i][2]

            lx = wx * self.ca[i] + wy * self.sa[i]
            ly = wx * self.sa[i] - wy * self.ca[i]
            lz = wz

            dx = lx - self.root_j1
            dy = ly
            a0 = -math.atan2(dy, dx)

            radial = math.hypot(dx, dy) - self.j1_j2
            vertical = lz
            base = math.atan2(vertical, radial)
            lr2 = radial * radial + vertical * vertical
            lr = math.sqrt(lr2)

            c1 = (lr2 + self.j2_j3**2 - self.j3_tip**2) / (2 * self.j2_j3 * lr)
            c2 = (lr2 - self.j2_j3**2 + self.j3_tip**2) / (2 * self.j3_tip * lr)
            c1 = max(-1.0, min(1.0, c1))
            c2 = max(-1.0, min(1.0, c2))
            a1 = math.acos(c1)
            a2 = math.acos(c2)

            ang[i, 0] = a0
            ang[i, 1] = base + a1
            ang[i, 2] = -(a1 + a2)

        ang = ang.flatten()
        return np.rad2deg(ang) if degrees else ang

    def forward_kinematics_local(self, leg: int, q0: float, q1: float, q2: float) -> np.ndarray:
        """FK for one leg in WORLD frame (no body transform), for validating IK round-trip.

        q* are the IK output angles in radians: q0=coxa yaw, q1=femur abs angle,
        q2=tibia relative angle. Inverse of the equations in inverse_kinematics.
        """
        # planar 2-link arm in (radial, vertical); femur abs = q1, tibia abs = q1 + q2
        arm_radial = self.j2_j3 * math.cos(q1) + self.j3_tip * math.cos(q1 + q2)
        arm_vertical = self.j2_j3 * math.sin(q1) + self.j3_tip * math.sin(q1 + q2)
        total_radial = self.j1_j2 + self.root_j1 + arm_radial
        lz = arm_vertical
        # azimuth of leg plane: a0 = -atan2(ly, lx)  =>  atan2(ly,lx) = -a0
        lx = total_radial * math.cos(-q0)
        ly = total_radial * math.sin(-q0)
        # back to world (un-rotate by mount angle), add mount pos
        wx = lx * self.ca[leg] + ly * self.sa[leg]
        wy = lx * self.sa[leg] - ly * self.ca[leg]
        wz = lz
        return np.array([wx + self.mount_pos[leg][0], wy + self.mount_pos[leg][1], wz])


class GaitController:
    """Port of firmware/include/gait.h :: GaitController."""

    def __init__(self, reflex: "ReflexConfig | None" = None, arc_stance: bool = False):
        # arc_stance: during a turn, sweep the planted foot along the ARC about the instantaneous
        # centre of rotation instead of the straight chord between the stroke endpoints.
        # `stroke = v + omega x r` (commit c8d2b52) gives each foot the right instantaneous
        # velocity, but _stance_curve then moves it linearly, so mid-stance the foot is off the
        # body's true path by the arc's sagitta: 15 mm for an in-place turn at step_angle 0.8, and
        # 20 mm for forward-plus-turn. A planted foot that cannot follow the body can only slip.
        self.arc_stance = bool(arc_stance)
        self.phase = 0.0
        self.default_position = DEFAULT_FEET.copy()
        self.target_default_position = DEFAULT_FEET.copy()
        self.swing_start_position = DEFAULT_FEET.copy()
        self.foot_was_swinging = [False] * 6
        # Whether a foot holds station through its current swing, decided as the swing begins (gait.h swingHeld).
        self.swing_held = [False] * 6
        # Swing progress each leg stood at when step() started the cycle from a standstill, 0 for a
        # swing begun inside the cycle; such a swing is replayed whole, from the floor, over the time
        # left to it, with its lift scaled to that time (gait.h swingEntry).
        self.swing_entry = np.zeros(6)
        self.cycle_running = False
        # The ease home runs from ease_from to ease_to and starts over whenever the feet are not where
        # it last put them or the stance changed (gait.h easeFeetHome).
        self.ease_from = np.zeros((6, 4))
        self.ease_to = np.zeros((6, 4))
        self.eased_feet = np.zeros((6, 4))
        self.eased_s = 0.0
        # A cycle started while the feet are away from its targets carries that offset and lets it go
        # along the same curve over the time the ease had left (gait.h carry).
        self.carry = np.zeros((6, 3))
        self.carried_s = 0.0
        self.carry_s = 0.0

        # contact-reflex state (unused while reflex is None)
        self.reflex = reflex
        self.phase_adj = np.zeros(6)   # per-leg phase hold, so a leg can wait for touchdown
        self.depth = np.zeros(6)       # mm this leg is reaching below nominal to find/keep ground
        self.elev_z = np.zeros(6)      # mm of extra step height from the elevator reflex
        self.hold_t = np.zeros(6)      # s each leg has been holding in late swing
        self.phase_scale = 1.0         # caller multiplies its phase advance by this
        self.open_run = np.zeros(6, dtype=int)    # consecutive samples reading open
        self.closed_run = np.zeros(6, dtype=int)  # consecutive samples reading closed
        self.stance_steps = np.zeros(6, dtype=int)  # control steps since this leg entered stance
        self._last_phase = 0.0

    @staticmethod
    def _stance_curve(length, angle, depth, phase, point):
        step = length * (1.0 - 2.0 * phase)
        point[0] += step * math.cos(angle)
        point[1] += step * math.sin(angle)
        if length != 0.0:
            point[2] = depth * math.cos((math.pi * step) / (2.0 * length))

    @staticmethod
    def _bezier_curve(length, angle, height, phase, point):
        x_polar = math.cos(angle)
        z_polar = math.sin(angle)
        # Both power tables multiply up from 1, as gait.h's do: dividing down from (1 - phase)^11 loses every
        # weight once that power is zero, at the very end of the swing.
        phase_power = [1.0]
        inv_phase_power = [1.0]
        for _ in range(11):
            phase_power.append(phase_power[-1] * phase)
            inv_phase_power.append(inv_phase_power[-1] * (1.0 - phase))
        for i in range(12):
            b = COMBINATORIAL_VALUES[i] * phase_power[i] * inv_phase_power[11 - i]
            point[0] += b * BEZIER_STEPS[i] * length * x_polar
            point[1] += b * BEZIER_STEPS[i] * length * z_polar
            point[2] += b * BEZIER_HEIGHTS[i] * height

    def _phase_params(self, phase, stand_frac, depth, height):
        if phase < stand_frac:
            return phase / stand_frac, self._stance_curve, -depth
        return _swing_progress(phase, stand_frac), self._bezier_curve, height

    def _start_cycle(self, gait: GaitState) -> None:
        for i in range(6):
            phase = math.fmod(self.phase + gait.offset[i], 1.0)
            self.swing_entry[i] = _swing_progress(phase, gait.stand_frac) if phase >= gait.stand_frac else 0.0
            # Every swing starts from where its foot stands now (gait.h startCycle).
            self.foot_was_swinging[i] = False
        self.cycle_running = True

    @staticmethod
    def _signed_stride(gait: GaitState) -> float:
        return math.hypot(gait.step_x, gait.step_y) * (-1 if gait.step_x < 0 else 1)

    def set_default_foot_target(self, target: np.ndarray) -> None:
        """Port of setDefaultFootTarget: feet migrate to `target` one swing at a time."""
        self.target_default_position = np.array(target, dtype=float)

    def has_pending_stance_change(self, epsilon: float = 0.5) -> bool:
        return bool(np.any(np.abs(self.default_position - self.target_default_position) > epsilon))

    def foot_at_target(self, i: int, epsilon: float = 0.5) -> bool:
        return bool(np.all(np.abs(self.default_position[i] - self.target_default_position[i]) <= epsilon))

    @staticmethod
    def _minimum_jerk(s: float) -> float:
        return s * s * s * (10.0 - 15.0 * s + 6.0 * s * s)

    def _ease_time_left(self, body: BodyState) -> float:
        return FEET_EASE_S - self.eased_s if np.array_equal(body.feet, self.eased_feet) else FEET_EASE_S

    def _apply_carry(self, body: BodyState, dt: float) -> None:
        if self.carried_s >= self.carry_s:
            return
        self.carried_s = min(self.carried_s + dt, self.carry_s)
        body.feet[:, :3] += self.carry * (1.0 - self._minimum_jerk(self.carried_s / self.carry_s))

    def _ease_feet_home(self, body: BodyState, dt: float) -> None:
        """Port of easeFeetHome: 10s^3 - 15s^4 + 6s^5 from where the feet were left to the stance."""
        if not np.array_equal(body.feet, self.eased_feet) or not np.array_equal(self.default_position, self.ease_to):
            self.ease_from = np.array(body.feet, dtype=float)
            self.ease_to = self.default_position.copy()
            self.eased_s = 0.0
        self.eased_s = min(self.eased_s + dt, FEET_EASE_S)
        blend = self._minimum_jerk(self.eased_s / FEET_EASE_S)
        self.eased_feet = self.ease_from + (self.ease_to - self.ease_from) * blend
        body.feet = self.eased_feet.copy()

    def generate_feet(self, gait: GaitState, body: BodyState,
                      contacts=None, dt: float = 0.0, repositioning: bool = False) -> None:
        """Generate feet at the CURRENT self.phase (does NOT advance phase).

        Used by `phase_gait` control mode where the policy owns the phase. When a ReflexConfig is
        attached and `contacts` (6 per-foot booleans) is supplied, per-leg contact reflexes adjust
        phase and step height; otherwise this is the plain open-loop gait.

        `repositioning` marks a stance-change cycle with no locomotion command, where a foot that
        already stands on its target holds station instead of stepping (gait.h generateFeet).
        """
        reflexive = self.reflex is not None and contacts is not None
        dphase = math.fmod(self.phase - self._last_phase + 1.0, 1.0) if reflexive else 0.0
        self._last_phase = self.phase

        new_feet = self.default_position.copy()
        n_stance = n_loaded = 0
        for i in range(6):
            # `%` not fmod: phase_adj accumulates negative while a leg's phase is held, and fmod
            # keeps the sign, which would push the phase out of [0,1) and evaluate the stance curve
            # at a negative parameter. The firmware has no phase_adj, so the two agree without it.
            phase = (self.phase + gait.offset[i] + self.phase_adj[i]) % 1.0
            is_swinging = phase >= gait.stand_frac
            if is_swinging and not self.foot_was_swinging[i]:
                self.swing_start_position[i] = self.default_position[i].copy()
                self.swing_held[i] = repositioning and self.foot_at_target(i)
            # A swing once begun is finished: decided anew each tick, a foot swinging for a small offset came
            # within reach of its target mid-swing and dropped to the floor in one tick.
            hold_station = repositioning and (self.swing_held[i] if is_swinging else self.foot_at_target(i))
            if reflexive and self.foot_was_swinging[i] and not is_swinging:
                self._on_touchdown(i)
            self.foot_was_swinging[i] = is_swinging
            if not is_swinging:
                self.swing_entry[i] = 0.0
            entry = self.swing_entry[i]
            progress = (_swing_progress(phase, gait.stand_frac) - entry) / (1.0 - entry) if is_swinging else 0.0
            if is_swinging and not hold_station:
                # A swinging foot carries its resting position from where the swing began to the
                # target, so a stance change lands one foot at a time.
                self.default_position[i] = _lerp(self.swing_start_position[i],
                                                 self.target_default_position[i], progress)

            rx, ry = self.default_position[i][0], self.default_position[i][1]
            stroke_x = gait.step_x + gait.step_angle * (-ry)   # translation + (omega x r): radius-scaled turn
            stroke_y = gait.step_y + gait.step_angle * (rx)
            stroke = math.hypot(stroke_x, stroke_y)
            direction = math.atan2(stroke_y, stroke_x)

            height = gait.step_height + (self.elev_z[i] if reflexive else 0.0)
            ph_norm, curve_fn, amp = self._phase_params(
                phase, gait.stand_frac, gait.step_depth, height
            )
            if is_swinging:
                ph_norm = progress
                amp *= 1.0 - entry
            delta = [0.0, 0.0, 0.0]
            if not hold_station:
                curve_fn(stroke / 2.0, direction, amp, ph_norm, delta)
            if self.arc_stance and not is_swinging and not hold_station and abs(gait.step_angle) > 1e-6:
                # _arc_stance_xy returns the OFFSET from the chord, so it adds to the stance
                # displacement rather than replacing it. delta[2] (the depth curve) is unchanged.
                ax, ay = self._arc_stance_xy(gait, rx, ry, ph_norm)
                delta[0] += ax
                delta[1] += ay
            if reflexive:
                delta[2] += self._reflex_z(i, is_swinging, ph_norm, delta[2], bool(contacts[i]),
                                           dphase, dt)
                n_stance += 0 if is_swinging else 1
                n_loaded += 1 if contacts[i] else 0
            for j in range(3):
                new_feet[i][j] = self.default_position[i][j] + delta[j]
            new_feet[i][3] = 1.0

        if reflexive and self.reflex.slow_when_unsupported:
            # Too few feet carrying load for this part of the cycle means the last touchdown did not
            # land where it was planned; slow the shared clock instead of striding on regardless.
            self.phase_scale = self.reflex.slow_factor if n_loaded < n_stance - 1 else 1.0
        body.feet = new_feet

    @staticmethod
    def _arc_stance_xy(gait: GaitState, rx: float, ry: float, ph_norm: float):
        """Foot XY displacement for a stance that follows the body's actual rotation.

        The instantaneous centre of rotation is where the body-frame velocity field vanishes:
        `v + omega x c = 0`, i.e. `c = (-step_y, step_x) / step_angle`. Over one stance the body
        turns by `step_angle`, so relative to the body the foot rotates about `c` by the same angle
        the other way.

        Anchoring matters: the arc is re-centred so its two ENDPOINTS coincide with the linear
        stroke's, and the curvature appears as an outward bulge at mid-stance. Anchoring at
        mid-stance instead would move the endpoints by the full 15 mm and break the swing, which
        still plans a straight chord between them. The residual is the 2.7 % difference between
        arc length `ang*R` and chord `2*R*sin(ang/2)`, which is not worth correcting.

        Computed as a perpendicular offset from the chord rather than by rotating about `c`.
        Rotating about the centre means forming `c = (-step_y, step_x)/ang`, which diverges as the
        turn rate goes to zero -- and `step_angle` is never exactly zero, because `yaw_comp` adds a
        velocity-proportional term even on a straight command. The subtraction of two huge nearly
        equal vectors then loses all precision, which showed up as a spurious effect on a
        forward-only control command. Here the whole correction carries a factor that vanishes
        linearly with `ang`, so straight-line walking is untouched by construction.
        """
        ang = gait.step_angle
        stroke_x = gait.step_x + ang * (-ry)
        stroke_y = gait.step_y + ang * rx
        # (p0 - c) = (stroke_y, -stroke_x) / ang, so the offset from the chord is
        #   [cos(ang*(p-1/2)) - cos(ang/2)] * (p0 - c),
        # whose scalar factor is O(ang) and stays well conditioned.
        k = (math.cos(ang * (ph_norm - 0.5)) - math.cos(0.5 * ang)) / ang
        return k * stroke_y, -k * stroke_x

    def _on_touchdown(self, i):
        """Per-cycle bookkeeping at the swing->stance transition."""
        r = self.reflex
        self.elev_z[i] *= r.elev_decay
        self.phase_adj[i] = 0.0
        self.hold_t[i] = 0.0
        self.open_run[i] = 0
        self.closed_run[i] = 0

    def _reflex_z(self, i, is_swinging, ph_norm, planned_z, contact, dphase, dt):
        """Vertical foot correction (mm) from the contact reflexes, and the phase hold."""
        r = self.reflex
        if contact:
            self.closed_run[i] += 1
            self.open_run[i] = 0
        else:
            self.open_run[i] += 1
            self.closed_run[i] = 0
        loaded = self.closed_run[i] >= 1
        unloaded = self.open_run[i] >= r.debounce

        if is_swinging:
            self.stance_steps[i] = 0
            if r.elevator and loaded and planned_z >= r.elev_trigger:
                self.elev_z[i] = min(r.elev_max, self.elev_z[i] + r.elev_step)
            return 0.0   # mid-swing clearance is never traded away
        self.stance_steps[i] += 1

        late = r.search_grace <= self.stance_steps[i] and ph_norm < r.search_window
        if r.search and late and unloaded:
            self.depth[i] = min(r.search_max, self.depth[i] + r.search_rate * dt)
            if r.hold_phase and self.hold_t[i] < r.hold_max_s:
                self.hold_t[i] += dt
                self.phase_adj[i] -= dphase          # hold this leg; the others keep going
        elif loaded:
            self.depth[i] = max(0.0, self.depth[i] - r.release_rate * dt)
            self.hold_t[i] = 0.0
        return -self.depth[i] if r.ground_follow else 0.0

    def advance_phase(self, gait: GaitState, dt: float, repositioning: bool = False) -> None:
        """Firmware phase advance: an explicit phase_rate wins, else speed scales with stride / turn.

        A repositioning cycle runs at plain step_speed (gait.h step).
        """
        if repositioning:
            speed = gait.step_speed
        elif gait.phase_rate > 0.0:
            speed = gait.phase_rate
        else:
            speed_factor = max(abs(self._signed_stride(gait)) / 25.0, abs(gait.step_angle) * 1.5)
            speed = gait.step_speed * min(max(speed_factor, 0.75), 1.5)
        self.phase = math.fmod(self.phase + dt * speed, 1.0)

    def set_phase(self, phase: float) -> None:
        self.phase = math.fmod(phase, 1.0)

    def step(self, gait: GaitState, body: BodyState, dt: float) -> None:
        """Faithful firmware step: ease the feet home when idle, reposition feet whose resting position
        changed, else advance + generate."""
        is_moving = gait_is_commanded(gait)
        repositioning = not is_moving and self.has_pending_stance_change()
        if not is_moving and not repositioning:
            self._ease_feet_home(body, dt)
            self.phase = 0.0
            self.cycle_running = False
            return
        self.advance_phase(gait, dt, repositioning)
        if self.cycle_running:
            self.generate_feet(gait, body, repositioning=repositioning)
        else:
            carry_time = self._ease_time_left(body)
            feet_left = np.array(body.feet, dtype=float)
            self._start_cycle(gait)
            self.generate_feet(gait, body, repositioning=repositioning)
            self.carry = feet_left[:, :3] - body.feet[:, :3]
            self.carry_s, self.carried_s = carry_time, 0.0
        self._apply_carry(body, dt)


