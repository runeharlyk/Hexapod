"""Emit the climb walk's envelope as a firmware header: the stroke geometry of its one posture, a lift above the classic
walk's 40 mm on a raised body, measured as export_envelope.py measures every grid point of the classic walk's.

The classic lift, (s1 + 1) * 20 mm, stops at 40 mm, and in MuJoCo the classic walk at its tallest posture climbs a sharp
50 mm step and is stopped at the face of a 60 mm one (test_climb.py). A higher lift walks only on a raised body: at the
default stance the longest feasible forward stroke at a 70 mm lift is 0 at h 0, 48 mm at h -0.5 and 92 mm at h -0.75.
Measured on 2026-11-08 on WAVE at full speed, a 70 mm lift at h -0.75 climbed 60 mm and walked 32 mm/s on flat ground,
an 80 mm lift there 70 mm at 23 mm/s, and a 90 mm lift at h -1 80 mm at 16 mm/s; the default is the middle one.

  python export_climb.py
  python export_climb.py --lift 90 --h -1
"""

import argparse
import os

from export_envelope import _float, _nested
from src.robot import firmware_gait as fg
from src.robot import gait_envelope as ge

HEADER = os.path.join(os.path.dirname(__file__), "..", "firmware", "include", "gait_climb.h")
FEET_DISTANCE = 0.0  # fd: the climb stands on the neutral stance


def feet_scale(fd: float) -> float:
    low, high = ge.FEET_SCALE_RANGE
    return low + (fd + 1.0) / 2.0 * (high - low)


def emit_header(lift: float, h: float, path: str) -> str:
    zm, scale = h * ge.BODY_HEIGHT_MM, feet_scale(FEET_DISTANCE)
    if not ge.walkable_at(lift, zm, scale, fg.STANCE_DEFAULT):
        raise SystemExit(f"a {lift} mm lift does not walk at h {h}")
    samples = [ge.geometry_samples_at(axis, lift, zm, scale, fg.STANCE_DEFAULT) for axis in ge.AXES]
    banner = f"""#pragma once

// GENERATED by simulation/export_climb.py -- do not edit by hand.
// Regenerate: cd simulation && uv run python export_climb.py --lift {lift:g} --h {h:g}
//
// The climb walk's one posture in the default stance, a LIFT_MM lift on a body at BODY_HEIGHT (the h posture command)
// over the neutral stance (fd {FEET_DISTANCE:g}), and its gait-independent geometry per axis as gait_envelope.h holds a
// grid point's: the longest feasible stroke, and the peak joint rate per unit of swing and stance progress (kappa) at
// STROKE_SAMPLES strokes, sample k at (k + 1) / STROKE_SAMPLES of the longest, feasible by the same checks.
// STROKE_MAX, KAPPA_SWING and KAPPA_STANCE are indexed [axis] and [axis][k], axis 0 forward (mm), 1 lateral (mm), 2 yaw
// (rad).

namespace gait_climb {{

constexpr float LIFT_MM = {float(lift)!r}f;
constexpr float BODY_HEIGHT = {float(h)!r}f;
constexpr float FEET_DISTANCE = {FEET_DISTANCE!r}f;
constexpr int STROKE_SAMPLES = {ge.STROKE_SAMPLES};
constexpr float TRAVEL_MARGIN_DEG = {ge.TRAVEL_MARGIN_DEG}f;  // joint travel kept in reserve by every stroke
constexpr float CLEARANCE_MM = {ge.LEG_CLEARANCE_MM}f;  // leg-pair clearance kept by every stroke
constexpr float STATIC_MARGIN_MM = {ge.STATIC_MARGIN_MM}f;  // body centre to support edge, kept by every stroke

constexpr float STROKE_MAX[3] = {_nested([s[0] for s in samples], _float)};

constexpr float KAPPA_SWING[3][STROKE_SAMPLES] = {_nested([[round(k, 4) for k in s[1]] for s in samples], _float)};

constexpr float KAPPA_STANCE[3][STROKE_SAMPLES] = {_nested([[round(k, 4) for k in s[2]] for s in samples], _float)};

}}  // namespace gait_climb
"""
    path = os.path.abspath(path)
    with open(path, "w", newline="\n") as f:
        f.write(banner)
    for axis, (stroke, _, _) in zip(ge.AXES, samples):
        print(f"  {axis:8} longest stroke {stroke:g}")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lift", type=float, default=80.0, help="mm")
    ap.add_argument("--h", type=float, default=-0.75, help="the body height posture command, zm = h * 50 mm")
    args = ap.parse_args()
    print(f"wrote {emit_header(args.lift, args.h, HEADER)}")


if __name__ == "__main__":
    main()
