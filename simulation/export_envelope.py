"""Emit the gait speed envelope as a firmware header and a JSON table.

The firmware maps the stick onto a fraction of each gait's top speed and clamps the posture to the walkable region.
Both come from this sweep, so `firmware/include/gait_envelope.h` is a build artifact of the port and the servo speed.

  python export_envelope.py
  python export_envelope.py --servo-rad-s 12.0
"""

import argparse
import json
import os

import numpy as np

from src.robot import gait_envelope as ge

HEADER = os.path.join(os.path.dirname(__file__), "..", "firmware", "include", "gait_envelope.h")
TABLE_JSON = os.path.join(os.path.dirname(__file__), "src", "resources", "gait_envelope.json")
INDENT = "    "


def _nested(values, fmt, depth=1):
    if not isinstance(values, list):
        return fmt(values)
    if not isinstance(values[0], list):
        return "{" + ", ".join(fmt(v) for v in values) + "}"
    rows = (",\n" + INDENT * depth).join(_nested(v, fmt, depth + 1) for v in values)
    return "{\n" + INDENT * depth + rows + "\n" + INDENT * (depth - 1) + "}"


def _float(v):
    return f"{v:.4f}f"


def _per_gait(table, key):
    return [[table["gaits"][name][axis][key] for axis in ge.AXES] for name in ge.GAIT_NAMES]


def emit_header(table, path):
    n = len(table["grid"])
    banner = f"""#pragma once

#include <cstdint>

// GENERATED by simulation/export_envelope.py -- do not edit by hand.
// Regenerate: cd simulation && uv run python export_envelope.py --servo-rad-s {table["servo_rad_s"]}
//
// Top body speed per gait over the posture grid, the stroke that reaches it, and the postures that can walk at all.
// A grid axis holds a posture command in [-1, 1] at {2 / (n - 1)} steps: s1 (step height), h (body height), fd (feet distance).
// Tables are indexed [s1][h][fd]; V_MAX and STROKE are indexed [gait][axis][s1][h][fd], gait = GaitType 0-3
// (TRI_GATE, BI_GATE, WAVE, RIPPLE) and axis 0 forward (mm/s, mm), 1 lateral (mm/s, mm), 2 yaw (rad/s, rad).

namespace gait_envelope {{

constexpr int GRID_N = {n};
constexpr float SERVO_RAD_S = {table["servo_rad_s"]}f;  // servo speed the speeds were bounded by
constexpr float CADENCE_MAX = {table["cadence_max"]}f;  // cycles/s
constexpr float DEFAULT_SPEED_FRACTION = {table["default_speed_fraction"]}f;  // of V_MAX at stick s = 0; s = 1 reaches 1

constexpr float STAND_FRAC[4] = {_nested([table["gaits"][name]["stand_frac"] for name in ge.GAIT_NAMES], lambda v: f"{v:.8f}f")};

constexpr uint8_t WALKABLE[{n}][{n}][{n}] = {_nested(np.array(table["walkable"], dtype=int).tolist(), str)};

constexpr float V_MAX[4][3][{n}][{n}][{n}] = {_nested(_per_gait(table, "v_max"), _float)};

constexpr float STROKE[4][3][{n}][{n}][{n}] = {_nested(_per_gait(table, "stroke"), _float)};

}}  // namespace gait_envelope
"""
    path = os.path.abspath(path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(banner)
    return path


def emit_json(table, path):
    path = os.path.abspath(path)
    with open(path, "w", newline="\n") as f:
        json.dump(table, f, separators=(",", ":"))
        f.write("\n")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--servo-rad-s", type=float, default=ge.DEFAULT_SERVO_RAD_S)
    args = ap.parse_args()

    table = ge.build_table(args.servo_rad_s)
    print(f"wrote {emit_header(table, HEADER)}")
    print(f"wrote {emit_json(table, TABLE_JSON)}")
    print(f"  servo speed {args.servo_rad_s} rad/s, cadence cap {ge.CADENCE_MAX} cycles/s")
    centre = len(ge.GRID) // 2
    for name in ge.GAIT_NAMES:
        speeds = [table["gaits"][name][axis]["v_max"][centre][centre][centre] for axis in ge.AXES]
        print(f"  {name:8} default posture  forward {speeds[0]:6.1f} mm/s  lateral {speeds[1]:6.1f} mm/s  "
              f"yaw {speeds[2]:5.2f} rad/s")


if __name__ == "__main__":
    main()
