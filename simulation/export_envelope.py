"""Emit the gait speed envelope of every stance as a firmware header and a JSON table.

The firmware derives each gait's stroke and top cadence at a stride from the stroke geometry, and clamps the posture to
the walkable region. Both come from this sweep, so `firmware/include/gait_envelope.h` is a build artifact of the port,
the servo speed and the legs' clearance.

  python export_envelope.py
  python export_envelope.py --servo-rad-s 12.0
"""

import argparse
import json
import os
import time

import numpy as np

from src.robot import firmware_gait as fg
from src.robot import gait_envelope as ge

HEADER = os.path.join(os.path.dirname(__file__), "..", "firmware", "include", "gait_envelope.h")
TABLE_JSON = os.path.join(os.path.dirname(__file__), "src", "resources", "gait_envelope.json")
INDENT = "    "


def _nested(values, fmt, depth=1):
    if not isinstance(values, list):
        return fmt(values)
    if not isinstance(values[0], list):
        return "{" + ", ".join(fmt(v) for v in values) + "}"
    rows = (",\n" + INDENT * depth).join(_nested(v, fmt, depth + 1) for v in values)
    return "{\n" + INDENT * depth + rows + "\n" + INDENT * (depth - 1) + "}"


def _float(v):
    return f"{v:.4f}f"


def _stances(table):
    return [table["stances"][name] for name in fg.STANCE_NAMES]


def _radii(table):
    """The capsule radii the clearance was judged with, one constant per segment."""
    return "\n".join(f"constexpr float {segment.upper()}_RADIUS_MM = {radius}f;  // capsule the clearance was judged with"
                     for segment, radius in table["link_radius_mm"].items())


def _walkable(table):
    return np.array([stance["walkable"] for stance in _stances(table)], dtype=int).tolist()


def _per_axis(table, key):
    return [[stance[key][axis] for axis in ge.AXES] for stance in _stances(table)]


def emit_header(table, path):
    n = len(table["grid"])
    walk_axes = ", ".join(f"{name} {table['stances'][name]['walk_axis']}" for name in fg.STANCE_NAMES)
    banner = f"""#pragma once

#include <cstdint>

// GENERATED by simulation/export_envelope.py -- do not edit by hand.
// Regenerate: cd simulation && uv run python export_envelope.py --servo-rad-s {table["servo_rad_s"]}
//
// Per stance, the postures that can walk at all, and the gait-independent geometry per axis: the longest feasible
// stroke, and the peak joint rate per unit of swing and stance progress (kappa) at STROKE_SAMPLES strokes, sample k at
// (k + 1) / STROKE_SAMPLES of the longest.
// A stroke is feasible within joint travel less TRAVEL_MARGIN_DEG and reach, with every leg pair CLEARANCE_MM apart
// and {table["clearance_reserve_mm"]} mm to spare over every classic timing's cycle; a posture walks where it strides
// 20 mm along the axis its stance walks ({walk_axes}).
// A gait with stand fraction d at stroke s and cadence f peaks at f * max(kappaSwing / (1 - d), kappaStance / d).
// A grid axis holds a posture command in [-1, 1] at {2 / (n - 1)} steps: s1 (step height), h (body height), fd (feet distance).
// WALKABLE is indexed [stance][s1][h][fd], STAND_FRAC by GaitType 0-3 (TRI_GATE, BI_GATE, WAVE, RIPPLE).
// STROKE_MAX, KAPPA_SWING and KAPPA_STANCE are indexed [stance][axis][s1][h][fd] and [stance][axis][s1][h][fd][k], stance
// by Stance ({", ".join(name.upper() for name in fg.STANCE_NAMES)}), axis 0 forward (mm), 1 lateral (mm), 2 yaw (rad).

namespace gait_envelope {{

constexpr int GRID_N = {n};
constexpr int STROKE_SAMPLES = {ge.STROKE_SAMPLES};
constexpr int STANCES = {len(fg.STANCE_NAMES)};
constexpr float SERVO_RAD_S = {table["servo_rad_s"]}f;  // servo speed the speeds were bounded by
constexpr float CADENCE_MAX = {table["cadence_max"]}f;  // cycles/s
constexpr float TRAVEL_MARGIN_DEG = {table["travel_margin_deg"]}f;  // joint travel kept in reserve by every stroke
constexpr float CLEARANCE_MM = {table["leg_clearance_mm"]}f;  // leg-pair clearance kept by every stroke
{_radii(table)}
constexpr float DEFAULT_SPEED_FRACTION = {table["default_speed_fraction"]}f;  // of the top speed at stick s = 0; s = 1 reaches 1

constexpr float STAND_FRAC[4] = {_nested(table["stand_frac"], lambda v: f"{v:.8f}f")};

constexpr uint8_t WALKABLE[STANCES][{n}][{n}][{n}] = {_nested(_walkable(table), str)};

constexpr float STROKE_MAX[STANCES][3][{n}][{n}][{n}] = {_nested(_per_axis(table, "stroke_max"), _float)};

constexpr float KAPPA_SWING[STANCES][3][{n}][{n}][{n}][STROKE_SAMPLES] = {_nested(_per_axis(table, "kappa_swing"), _float)};

constexpr float KAPPA_STANCE[STANCES][3][{n}][{n}][{n}][STROKE_SAMPLES] = {_nested(_per_axis(table, "kappa_stance"), _float)};

}}  // namespace gait_envelope
"""
    path = os.path.abspath(path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(banner)
    return path


def emit_json(table, path):
    path = os.path.abspath(path)
    with open(path, "w", newline="\n") as f:
        json.dump(table, f, separators=(",", ":"))
        f.write("\n")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--servo-rad-s", type=float, default=ge.DEFAULT_SERVO_RAD_S)
    args = ap.parse_args()

    start = time.monotonic()
    table = ge.build_table(args.servo_rad_s)
    print(f"wrote {emit_header(table, HEADER)}")
    print(f"wrote {emit_json(table, TABLE_JSON)}")
    print(f"  servo speed {args.servo_rad_s} rad/s, cadence cap {ge.CADENCE_MAX} cycles/s, "
          f"leg clearance {ge.LEG_CLEARANCE_MM} mm, {time.monotonic() - start:.0f} s")
    fg.load_gait_envelope.cache_clear()
    for stance, stance_name in enumerate(fg.STANCE_NAMES):
        for gait_type, name in enumerate(ge.GAIT_NAMES):
            speeds = [fg.envelope_at(gait_type, axis, 0.0, 0.0, 0.0, 0.0, stance)[0] for axis in range(len(ge.AXES))]
            print(f"  {stance_name:7} {name:8} default posture, speed-optimal stride  forward {speeds[0]:6.1f} mm/s  "
                  f"lateral {speeds[1]:6.1f} mm/s  yaw {speeds[2]:5.2f} rad/s")


if __name__ == "__main__":
    main()
