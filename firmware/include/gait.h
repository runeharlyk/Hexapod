#include <utils/math_utils.h>
#include <array>
#include <functional>
#include <kinematics.h>
#include <message_types.h>
#include <gait_tuned.h>

static constexpr float default_offset[6] = {0, 0.52, 0.08, 0.58, 0.16, 0.66};
static constexpr float default_stand_frac = 3.1 / 6;

struct gait_state_t {
    float step_height, step_x, step_y, step_angle, step_speed, step_depth, stand_frac;
    GaitType gait_type;
    float offset[6];
    // Explicit cadence in cycles/s. 0 = use the legacy stride-derived law below. The searched gaits
    // set it, because that law and the one they were optimized under disagree -- mildly when walking
    // forward (0.90-1.24x) and by 1.80x for an in-place turn, where the legacy CLIP floors cadence
    // at 0.75 cyc/s and the tuned gait wants 1.35. Last member, so existing aggregate initializers
    // stay valid and zero it.
    float phase_rate;
};

// Deadbands for "the gait is commanded to move". Stride is millimetres of foot travel; yaw is
// radians of body rotation per stance, and 0.005 rad across the 171 mm leg radius is 0.9 mm of foot
// travel -- the same order as the stride deadband. step_angle used to be tested against exact zero,
// which the command ramp below never reaches, so a single turn command left the cycle stepping in
// place for as long as the robot stayed powered.
static constexpr float GAIT_STRIDE_DEADBAND_MM = 2.0f;
static constexpr float GAIT_YAW_DEADBAND_RAD = 0.005f;

inline bool gaitIsCommanded(const gait_state_t& gait) {
    return std::fabs(gait.step_x) >= GAIT_STRIDE_DEADBAND_MM || std::fabs(gait.step_y) >= GAIT_STRIDE_DEADBAND_MM ||
           std::fabs(gait.step_angle) >= GAIT_YAW_DEADBAND_RAD;
}

// Stick -> command ranges for GaitType::TUNED. The searched gait is a velocity->gait map, so the
// stick becomes a velocity command over the envelope the search actually covered; commanding outside
// it asks for a gait nobody measured. These mirror CMD_VX/CMD_VY/CMD_YAW in hexapod_mj_env.py.
// They live here rather than in gait_tuned.h because that file is regenerated by
// simulation/export_gait.py, and rather than in MotionService because the host gait tests need them.
static constexpr float TUNED_CMD_VX_MAX = 0.45f;   // m/s forward
static constexpr float TUNED_CMD_VY_MAX = 0.12f;   // m/s lateral
static constexpr float TUNED_CMD_YAW_MAX = 1.0f;   // rad/s
// The s1 slider trims foot lift around tuned_gait::STEP_HEIGHT_MM rather than setting it from zero,
// so the operator keeps authority without discarding the parameter the terrain search cared most
// about. Note the trim is not symmetric in feasibility: the bottom stop is the only fully reachable
// setting, while the top stop exceeds femur travel at every stride.
static constexpr float TUNED_LIFT_TRIM_MM = 15.0f;

// Leaving a walk, the feet are eased home from wherever the cycle left them, lifted feet included,
// along 10s^3 - 15s^4 + 6s^5 over this long: a minimum-jerk path, at rest at both ends. Leika's
// easeFeet uses the same law and time.
static constexpr float FEET_EASE_S = 0.5f;

static constexpr float GAIT_SNAP_MM = 0.01f;
static constexpr float GAIT_SNAP_RAD = 1e-5f;
static constexpr float GAIT_SNAP_RATE = 1e-4f;
static constexpr float GAIT_SNAP_DEPTH = 1e-6f;

inline float approachf(float current, float target, float alpha, float eps) {
    const float next = lerpf(current, target, alpha);
    return std::fabs(target - next) <= eps ? target : next;
}

inline void approachGaitCommand(gait_state_t& current, const gait_state_t& target, float dt, float tau) {
    const float a = (tau <= 0.0f || dt <= 0.0f) ? 1.0f : 1.0f - expf(-dt / tau);
    current.step_x = approachf(current.step_x, target.step_x, a, GAIT_SNAP_MM);
    current.step_y = approachf(current.step_y, target.step_y, a, GAIT_SNAP_MM);
    current.step_angle = approachf(current.step_angle, target.step_angle, a, GAIT_SNAP_RAD);
    current.step_speed = approachf(current.step_speed, target.step_speed, a, GAIT_SNAP_RATE);
    current.step_height = approachf(current.step_height, target.step_height, a, GAIT_SNAP_MM);
    current.step_depth = approachf(current.step_depth, target.step_depth, a, GAIT_SNAP_DEPTH);
    // phase_rate 0 means "derive cadence from stride", not "stand still", so ramping across that
    // boundary would spend the whole transition at cadences neither law asks for. Ease only between
    // two explicit rates; otherwise switch outright.
    current.phase_rate = (current.phase_rate > 0.0f && target.phase_rate > 0.0f)
                             ? approachf(current.phase_rate, target.phase_rate, a, GAIT_SNAP_RATE)
                             : target.phase_rate;
}

// The command ramp the walk eases through. A change eases first order over tau, except a stop, which starts from the
// walk as it is:
// - Its stroke eases out through two first-order stages in a row. A single stage moves the stroke at its fastest from
//   the first tick, and a foot at the edge of its reach, where the joints turn furthest per millimetre, then moved up
//   to 1.8 times as fast as in the walk; two stages start it from rest.
// - Its cadence is scaled with the share of the stroke left. The stride law (phase_rate 0) stepped the shrinking stroke
//   at up to 1.5 cycles/s, faster than a slow gait walked it, and the walk's own cadence lifts the feet as fast over a
//   stroke near zero, a pace the envelope never measured.
// The virtual robot's stop and release rollouts pin that no stop leaves travel or moves a joint past the step bound.
// A walk on the stride law keeps it through the stop.
class GaitCommandRamp {
  public:
    void step(gait_state_t& live, const gait_state_t& target, float dt, float tau) {
        if (target.phase_rate > 0.0f || gaitIsCommanded(target) || !gaitIsCommanded(live)) {
            stopping = false;
            approachGaitCommand(live, target, dt, tau);
            return;
        }
        if (!stopping) {
            stopping = true;
            from = live;
            stage = live;
        }
        const float a = (tau <= 0.0f || dt <= 0.0f) ? 1.0f : 1.0f - expf(-dt / tau);
        stage.step_x = approachf(stage.step_x, target.step_x, a, GAIT_SNAP_MM);
        stage.step_y = approachf(stage.step_y, target.step_y, a, GAIT_SNAP_MM);
        stage.step_angle = approachf(stage.step_angle, target.step_angle, a, GAIT_SNAP_RAD);
        gait_state_t eased = target;
        eased.step_x = stage.step_x;
        eased.step_y = stage.step_y;
        eased.step_angle = stage.step_angle;
        approachGaitCommand(live, eased, dt, tau);
        live.phase_rate = gaitIsCommanded(live) ? from.phase_rate * strokeLeft(live) : 0.0f;
    }

  private:
    // The share of the stop's starting stroke left, along the axis that started furthest past its deadband: both stages
    // ease every axis alike.
    float strokeLeft(const gait_state_t& g) const {
        const float x = std::fabs(from.step_x) / GAIT_STRIDE_DEADBAND_MM,
                    y = std::fabs(from.step_y) / GAIT_STRIDE_DEADBAND_MM,
                    yaw = std::fabs(from.step_angle) / GAIT_YAW_DEADBAND_RAD;
        if (x >= y && x >= yaw) return std::fabs(g.step_x / from.step_x);
        if (y >= yaw) return std::fabs(g.step_y / from.step_y);
        return std::fabs(g.step_angle / from.step_angle);
    }

    bool stopping = false;
    gait_state_t from {};  // the walk the stop started from
    gait_state_t stage {}; // the first of the stroke's two stages
};

class GaitController {
  private:
    float phase = 0.0f;
    float defaultPosition[6][4] = {{122, 152, -66, 1},  {171, 0, -66, 1},  {122, -152, -66, 1},
                                   {-122, 152, -66, 1}, {-171, 0, -66, 1}, {-122, -152, -66, 1}};
    float targetDefaultPosition[6][4] = {{122, 152, -66, 1},  {171, 0, -66, 1},  {122, -152, -66, 1},
                                         {-122, 152, -66, 1}, {-171, 0, -66, 1}, {-122, -152, -66, 1}};
    float swingStartPosition[6][4] = {{122, 152, -66, 1},  {171, 0, -66, 1},  {122, -152, -66, 1},
                                      {-122, 152, -66, 1}, {-171, 0, -66, 1}, {-122, -152, -66, 1}};
    bool footWasSwinging[6] = {false, false, false, false, false, false};
    // Whether a foot holds station through its current swing, decided as the swing begins.
    bool swingHeld[6] = {false, false, false, false, false, false};
    // A cycle started from a standstill finds some legs mid-swing, since at phase 0 every offset past
    // stand_frac is already swinging; taken as is, the foot left the floor at that swing's height in
    // one tick. Such a swing is instead replayed whole, from the floor, over the time left to it, with
    // its lift scaled to that time so the foot rises no faster than in a full swing. swingEntry holds
    // the swing progress the cycle started at, 0 for a swing begun inside the cycle.
    float swingEntry[6] = {0, 0, 0, 0, 0, 0};
    bool cycleRunning = false;
    // The ease home runs from easeFrom to easeTo. It starts over whenever the feet are not where it
    // last put them or the stance changed: the walk, the policy or an animation moved them meanwhile.
    float easeFrom[6][4] = {};
    float easeTo[6][4] = {};
    float easedFeet[6][4] = {};
    float easedS = 0.0f;
    // A cycle started while the feet are away from its targets, mid-ease or left lifted by a stopped
    // walk, carries that offset and lets it go along the same curve over the time the ease had left,
    // instead of snapping the feet onto the cycle in one tick.
    float carry[6][3] = {};
    float carriedS = 0.0f;
    float carryS = 0.0f;
    static constexpr uint8_t BEZIER_POINTS = 12;
    static constexpr std::array<float, BEZIER_POINTS> COMBINATORIAL_VALUES = {
        combinatorial_constexpr(11, 0),  // 1
        combinatorial_constexpr(11, 1),  // 11
        combinatorial_constexpr(11, 2),  // 55
        combinatorial_constexpr(11, 3),  // 165
        combinatorial_constexpr(11, 4),  // 330
        combinatorial_constexpr(11, 5),  // 462
        combinatorial_constexpr(11, 6),  // 462
        combinatorial_constexpr(11, 7),  // 330
        combinatorial_constexpr(11, 8),  // 165
        combinatorial_constexpr(11, 9),  // 55
        combinatorial_constexpr(11, 10), // 11
        combinatorial_constexpr(11, 11)  // 1
    };

    alignas(32) static constexpr float BEZIER_STEPS[12] = {-1.0f, -1.4f, -1.5f, -1.5f, -1.5f, 0.0f,
                                                           0.0f,  0.0f,  1.5f,  1.5f,  1.4f,  1.0f};

    alignas(32) static constexpr float BEZIER_HEIGHTS[12] = {0.0f, 0.0f, 0.9f, 0.9f, 0.9f, 0.9f,
                                                             0.9f, 1.1f, 1.1f, 1.1f, 0.0f, 0.0f};

    void stanceCurve(const float length, const float angle, const float* depth, const float phase, float* point) {
        float step = length * (1.0f - 2.0f * phase);
        point[0] += step * std::cos(angle);
        point[1] += step * std::sin(angle);

        if (length != 0.0f) {
            // Pressed most mid-stance and level at both ends, along the stroke whatever its direction.
            point[2] = *depth * std::cos((M_PI * step) / (2.f * length));
        }
    }

    void bezierCurve(const float length, const float angle, const float* height, const float phase, float* point) {
        const float X_POLAR = std::cos(angle);
        const float Z_POLAR = std::sin(angle);

        // Both power tables are built by multiplying up from 1, never by dividing down from
        // (1 - phase)^11: that power underflows float32 near the end of a swing and a division
        // cannot recover the weights from zero.
        float phase_power[BEZIER_POINTS];
        float inv_phase_power[BEZIER_POINTS];
        phase_power[0] = 1.0f;
        inv_phase_power[0] = 1.0f;
        for (int i = 1; i < BEZIER_POINTS; i++) {
            phase_power[i] = phase_power[i - 1] * phase;
            inv_phase_power[i] = inv_phase_power[i - 1] * (1.0f - phase);
        }

        for (int i = 0; i < BEZIER_POINTS; i++) {
            float b = COMBINATORIAL_VALUES[i] * phase_power[i] * inv_phase_power[BEZIER_POINTS - 1 - i];
            point[0] += b * BEZIER_STEPS[i] * length * X_POLAR;
            point[1] += b * BEZIER_STEPS[i] * length * Z_POLAR;
            point[2] += b * BEZIER_HEIGHTS[i] * *height;
        }
    }

    void advancePhase(float dt, float velocity) { phase = std::fmod(phase + dt * velocity, 1.0f); }

    float legPhase(const gait_state_t& gait, int leg) const { return std::fmod(phase + gait.offset[leg], 1.0f); }

    static float swingProgress(float ph, float standFrac) { return (ph - standFrac) / (1.0f - standFrac); }

    void startCycle(const gait_state_t& gait) {
        for (int i = 0; i < 6; i++) {
            const float ph = legPhase(gait, i);
            swingEntry[i] = ph >= gait.stand_frac ? swingProgress(ph, gait.stand_frac) : 0.0f;
            // Every swing starts from where its foot stands now. A foot the last cycle left flagged as
            // swinging, as a stance change does with its last foot, would otherwise keep that swing's
            // start and pull its anchor back toward the stance it left.
            footWasSwinging[i] = false;
        }
        cycleRunning = true;
    }

    std::tuple<float, std::function<void(const float, const float, const float*, const float, float*)>, float>
    phaseParams(float phase, float standFrac, float depth, float height) {
        if (phase < standFrac) {
            return {phase / standFrac,
                    [this](const float l, const float a, const float* d, const float p, float* pt) {
                        this->stanceCurve(l, a, d, p, pt);
                    },
                    -depth};
        }
        return {swingProgress(phase, standFrac),
                [this](const float l, const float a, const float* h, const float p, float* pt) {
                    this->bezierCurve(l, a, h, p, pt);
                },
                height};
    }

    bool positionsMatch(const float lhs[6][4], const float rhs[6][4], float epsilon = 0.5f) const {
        for (int i = 0; i < 6; ++i) {
            for (int j = 0; j < 4; ++j) {
                if (std::fabs(lhs[i][j] - rhs[i][j]) > epsilon) return false;
            }
        }
        return true;
    }

    bool footAtTarget(int footIndex, float epsilon = 0.5f) const {
        for (int j = 0; j < 4; ++j) {
            if (std::fabs(defaultPosition[footIndex][j] - targetDefaultPosition[footIndex][j]) > epsilon) return false;
        }
        return true;
    }

    static float minimumJerk(float s) { return s * s * s * (10.0f - 15.0f * s + 6.0f * s * s); }

    float easeTimeLeft(const BodyStateMsg& body) const {
        return positionsMatch(body.feet, easedFeet, 0.0f) ? FEET_EASE_S - easedS : FEET_EASE_S;
    }

    void startCarry(const float feetLeft[6][4], const BodyStateMsg& body, float duration) {
        for (int i = 0; i < 6; ++i) {
            for (int j = 0; j < 3; ++j) carry[i][j] = feetLeft[i][j] - body.feet[i][j];
        }
        carryS = duration;
        carriedS = 0.0f;
    }

    void applyCarry(BodyStateMsg& body, float dt) {
        if (carriedS >= carryS) return;
        carriedS = std::min(carriedS + dt, carryS);
        const float remaining = 1.0f - minimumJerk(carriedS / carryS);
        for (int i = 0; i < 6; ++i) {
            for (int j = 0; j < 3; ++j) body.feet[i][j] += carry[i][j] * remaining;
        }
    }

    void easeFeetHome(BodyStateMsg& body, float dt) {
        if (!positionsMatch(body.feet, easedFeet, 0.0f) || !positionsMatch(defaultPosition, easeTo, 0.0f)) {
            COPY_2D_ARRAY_6x4(easeFrom, body.feet);
            COPY_2D_ARRAY_6x4(easeTo, defaultPosition);
            easedS = 0.0f;
        }
        easedS = std::min(easedS + dt, FEET_EASE_S);
        const float blend = minimumJerk(easedS / FEET_EASE_S);
        for (int i = 0; i < 6; ++i) {
            for (int j = 0; j < 4; ++j) easedFeet[i][j] = easeFrom[i][j] + (easeTo[i][j] - easeFrom[i][j]) * blend;
        }
        body.updateFeet(easedFeet);
    }

    void updateDefaultPositionTarget(int footIndex, float swingProgress) {
        for (int j = 0; j < 4; ++j) {
            defaultPosition[footIndex][j] =
                lerpf(swingStartPosition[footIndex][j], targetDefaultPosition[footIndex][j], swingProgress);
        }
    }

  public:
    GaitController() {}

    void setDefaultFootTarget(const float target[6][4]) { COPY_2D_ARRAY_6x4(targetDefaultPosition, target); }

    void snapDefaultFootTarget(const float target[6][4]) {
        COPY_2D_ARRAY_6x4(defaultPosition, target);
        COPY_2D_ARRAY_6x4(targetDefaultPosition, target);
        COPY_2D_ARRAY_6x4(swingStartPosition, target);
        for (bool &footSwinging : footWasSwinging) footSwinging = false;
        for (float& entry : swingEntry) entry = 0.0f;
        phase = 0.0f;
        cycleRunning = false;
    }

    bool hasPendingStanceChange() const { return !positionsMatch(defaultPosition, targetDefaultPosition); }

    void setGait(gait_state_t& gait) {
        switch (gait.gait_type) {
            case GaitType::TRI_GATE:
                gait.offset[0] = 0.0f;
                gait.offset[1] = 0.52f;
                gait.offset[2] = 0.08f;
                gait.offset[3] = 0.58f;
                gait.offset[4] = 0.16f;
                gait.offset[5] = 0.66f;
                gait.stand_frac = 3.1f / 6.0f;
                break;
            case GaitType::BI_GATE:
                gait.offset[0] = 0.0f;
                gait.offset[1] = 1.0f / 3.0f;
                gait.offset[2] = 2.0f / 3.0f;
                gait.offset[3] = 2.0f / 3.0f;
                gait.offset[4] = 1.0f / 3.0f;
                gait.offset[5] = 0.0f;
                gait.stand_frac = 2.1f / 6.0f;
                break;
            case GaitType::WAVE:
                gait.offset[0] = 0.0f;
                gait.offset[1] = 1.0f / 6.0f;
                gait.offset[2] = 2.0f / 6.0f;
                gait.offset[3] = 5.0f / 6.0f;
                gait.offset[4] = 4.0f / 6.0f;
                gait.offset[5] = 3.0f / 6.0f;
                gait.stand_frac = 5.0f / 6.0f;
                break;
            case GaitType::RIPPLE:
                gait.offset[0] = 0.0f;
                gait.offset[1] = 4.0f / 6.0f;
                gait.offset[2] = 2.0f / 6.0f;
                gait.offset[3] = 1.0f / 6.0f;
                gait.offset[4] = 5.0f / 6.0f;
                gait.offset[5] = 3.0f / 6.0f;
                gait.stand_frac = 5.0f / 6.0f;
                break;
            case GaitType::TUNED:
                // Searched coordination; the caller must also apply tuned_gait::STEP_HEIGHT_MM,
                // STEP_DEPTH_MM and RIDE_MM, which is what MotionService's WALK branch does.
                for (uint8_t i = 0; i < 6; ++i) gait.offset[i] = tuned_gait::OFFSET[i];
                gait.stand_frac = tuned_gait::STAND_FRAC;
                break;
            default: break;
        }
    }


    // repositioning: a stance-change cycle with no locomotion command, where feet already on
    // target hold station instead of stepping. Plain walking cycles pass false.
    void generateFeet(gait_state_t& gait, BodyStateMsg& body, bool repositioning = false) {
        float newFeet[6][4];
        COPY_2D_ARRAY_6x4(newFeet, defaultPosition);

        for (int i = 0; i < 6; i++) {
            const float ph = legPhase(gait, i);
            const bool isSwinging = ph >= gait.stand_frac;
            // A foot already standing where it belongs has nothing to fetch, so it holds station
            // rather than taking an empty step while the others catch up. Repositioning only: in
            // normal walking every foot sits at its default position and must still swing.
            if (isSwinging && !footWasSwinging[i]) {
                for (int j = 0; j < 4; ++j) {
                    swingStartPosition[i][j] = defaultPosition[i][j];
                }
                swingHeld[i] = repositioning && footAtTarget(i);
            }
            // A swing once begun is finished: decided anew each tick, a foot swinging for a small
            // offset came within reach of its target mid-swing and dropped to the floor in one tick.
            const bool holdStation = repositioning && (isSwinging ? swingHeld[i] : footAtTarget(i));
            footWasSwinging[i] = isSwinging;
            if (!isSwinging) swingEntry[i] = 0.0f;
            const float entry = swingEntry[i];
            const float progress = isSwinging ? (swingProgress(ph, gait.stand_frac) - entry) / (1.0f - entry) : 0.0f;

            if (isSwinging && !holdStation) updateDefaultPositionTarget(i, progress);

            const float rx = defaultPosition[i][0];
            const float ry = defaultPosition[i][1];
            const float strokeX = gait.step_x + gait.step_angle * (-ry);
            const float strokeY = gait.step_y + gait.step_angle * (rx);
            const float stroke = std::hypot(strokeX, strokeY);
            const float direction = std::atan2(strokeY, strokeX);

            float delta[3] = {0, 0, 0};
            if (!holdStation) {
                auto [phNorm, curveFn, amp] = phaseParams(ph, gait.stand_frac, gait.step_depth, gait.step_height);
                if (isSwinging) {
                    phNorm = progress;
                    amp *= 1.0f - entry;
                }
                curveFn(stroke / 2, direction, &amp, phNorm, delta);
            }

            for (int j = 0; j < 3; j++) {
                newFeet[i][j] = defaultPosition[i][j] + delta[j];
            }
            newFeet[i][3] = 1;
        }

        body.updateFeet(newFeet);
    }

    void setPhase(float p) { phase = std::fmod(p, 1.0f); }
    float getPhase() const { return phase; }

    // Whether the leg's foot is in the stance part of the cycle the last step walked. A step that ran no cycle eased
    // the feet home and swung none; a foot it lowers is still in the air for a while (KinematicOdometry::LIFTED_MM).
    bool inStance(const gait_state_t& gait, int leg) const {
        return !cycleRunning || legPhase(gait, leg) < gait.stand_frac;
    }

    // The phase of the cycle left before the leg's foot lifts: 0 for a foot in its swing, and never for a gait that is
    // not cycling.
    float phaseToLift(const gait_state_t& gait, int leg) const {
        return cycleRunning ? std::max(gait.stand_frac - legPhase(gait, leg), 0.0f) : INFINITY;
    }

    void step(gait_state_t& gait, BodyStateMsg& body, float dt) {
        const bool isMoving = gaitIsCommanded(gait);
        const bool isRepositioning = !isMoving && hasPendingStanceChange();

        if (!isMoving && !isRepositioning) {
            easeFeetHome(body, dt);
            phase = 0;
            cycleRunning = false;
            return;
        }

        const float length = std::hypot(gait.step_x, gait.step_y) * (gait.step_x < 0 ? -1 : 1);
        const float speed_factor = std::max(std::abs(length) / 25.f, std::abs(gait.step_angle) * 1.5f);
        const float speed =
            isRepositioning ? gait.step_speed
            : gait.phase_rate > 0.f ? gait.phase_rate
                                    : gait.step_speed * CLIP(speed_factor, 0.75, 1.5f);

        advancePhase(dt, speed);
        if (cycleRunning) {
            generateFeet(gait, body, isRepositioning);
        } else {
            const float carryTime = easeTimeLeft(body);
            float feetLeft[6][4];
            COPY_2D_ARRAY_6x4(feetLeft, body.feet);
            startCycle(gait);
            generateFeet(gait, body, isRepositioning);
            startCarry(feetLeft, body, carryTime);
        }
        applyCarry(body, dt);
    }
};
